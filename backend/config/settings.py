def _obrigatoria(nome: str) -> str:
    """Lê uma variável de ambiente; se faltar, o servidor recusa a ligar."""
    valor = os.environ.get(nome)
    if not valor:
        raise ImproperlyConfigured(
            f"Variável de ambiente {nome} não definida (veja o .env.example).")
    return valor


